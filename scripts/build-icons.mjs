import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { loadIcons } from "./icon-data.mjs";

const args = process.argv.slice(2);
assert.ok(
  args.length <= 1 && args.every((arg) => arg === "--check"),
  "Unknown icon build argument",
);
const rows = await loadIcons();
const definitions = rows
  .map(
    (row) =>
      `${row.id} -> #(${JSON.stringify(row.name)}, ${JSON.stringify(row.path)}, ${JSON.stringify(row.category)})`,
  )
  .join("\n");
const source = `// Generated by scripts/build-icons.mjs. Edit priv/icons instead.
import lustre/attribute.{type Attribute}
import lustre/element.{type Element}
import meridian_ui/internal/icon_svg

pub type Icon {
${rows.map((row) => row.id).join("\n")}
}

pub type Style {
  Auto
  Outline
  Soft
  Duotone
}

/// Decorative by default. Give the surrounding control an accessible name.
pub fn view(icon: Icon, attrs: List(Attribute(msg))) -> Element(msg) {
  view_with(icon, Auto, attrs)
}

/// Auto follows the root's component style. Brand marks keep their official shape.
pub fn view_with(icon: Icon, style: Style, attrs: List(Attribute(msg))) -> Element(msg) {
  let #(name, path, _) = definition(icon)
  icon_svg.view(name, path, case style {
    Auto -> "auto"
    Outline -> "outline"
    Soft -> "soft"
    Duotone -> "duotone"
  }, attrs)
}

pub fn name(icon: Icon) -> String { definition(icon).0 }
pub fn category(icon: Icon) -> String { definition(icon).2 }
pub fn all() -> List(Icon) { [${rows.map((row) => row.id).join(", ")}] }

fn definition(icon: Icon) -> #(String, String, String) {
  case icon {
${definitions}
  }
}
`;
const formatted = spawnSync("gleam", ["format", "--stdin"], {
  input: source,
  encoding: "utf8",
});
assert.equal(formatted.status, 0, formatted.stderr);
const output = "src/meridian_ui/icon.gleam";
if (args.includes("--check"))
  assert.ok(
    (await readFile(output, "utf8")) === formatted.stdout,
    "Run npm run build:icons to refresh the icon catalogue",
  );
else await writeFile(output, formatted.stdout);
console.log(`Verified ${rows.length} SVG icons from domain data`);
