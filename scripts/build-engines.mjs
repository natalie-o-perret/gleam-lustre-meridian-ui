import assert from "node:assert/strict";
import { build } from "esbuild";
import { readFile, writeFile, mkdir, readdir } from "node:fs/promises";
import { resolve, relative } from "node:path";

const output = "src/meridian_ui/internal/vendor";
const check = process.argv.includes("--check");
const packages = new Set();
if (!check) await mkdir(output, { recursive: true });
for (const name of ["mask", "charts", "calendar", "editor"]) {
  const result = await build({
    entryPoints: [`scripts/engines/${name}.mjs`],
    bundle: true,
    format: "esm",
    platform: "browser",
    target: "es2022",
    minify: true,
    legalComments: "eof",
    metafile: true,
    write: false,
    outfile: `${output}/${name}.mjs`,
  });
  const file = result.outputFiles[0];
  if (check)
    assert.equal(
      await readFile(file.path, "utf8"),
      file.text,
      `${name} bundle is stale`,
    );
  else await writeFile(file.path, file.text);
  for (const input of Object.keys(result.metafile.inputs)) {
    if (!input.startsWith("node_modules/")) continue;
    const match = [
      ...input.matchAll(/(?:^|\/)node_modules\/(?:@[^/]+\/)?[^/]+/g),
    ].at(-1);
    packages.add(resolve(input.slice(0, match.index + match[0].length)));
  }
}
let licences =
  "# Bundled open-source engines\n\nGenerated by `npm run build:engines` from the pinned lockfile.\n";
for (const path of [...packages].sort()) {
  const metadata = JSON.parse(
    await readFile(resolve(path, "package.json"), "utf8"),
  );
  const names = (await readdir(path))
    .filter((name) => /^(licen[cs]e|notice|copying)([.-]|$)/i.test(name))
    .sort();
  assert.ok(
    names.length,
    `${relative(process.cwd(), path)} has no licence notice`,
  );
  licences += `\n## ${metadata.name} ${metadata.version} (${metadata.license})\n`;
  for (const name of names)
    licences += `\n### ${name}\n\n\`\`\`text\n${(await readFile(resolve(path, name), "utf8")).trim()}\n\`\`\`\n`;
}
if (check)
  assert.equal(
    await readFile(`${output}/LICENCES.md`, "utf8"),
    licences,
    "Licence notices are stale",
  );
else await writeFile(`${output}/LICENCES.md`, licences);
console.log(`Verified 4 bundles and ${packages.size} package notices`);
